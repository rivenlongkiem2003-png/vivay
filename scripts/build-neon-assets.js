const { readFileSync, writeFileSync } = require('fs');
const { join } = require('path');

const root = process.cwd();
const assets = {
    '/': ['index.html', 'text/html; charset=utf-8'],
    '/index.html': ['index.html', 'text/html; charset=utf-8'],
    '/detail.html': ['detail.html', 'text/html; charset=utf-8'],
    '/admin.html': ['admin.html', 'text/html; charset=utf-8'],
    '/index.css': ['index.css', 'text/css; charset=utf-8'],
    '/detail.css': ['detail.css', 'text/css; charset=utf-8'],
    '/admin.css': ['admin.css', 'text/css; charset=utf-8'],
    '/theme.css': ['theme.css', 'text/css; charset=utf-8'],
    '/login.js': ['login.js', 'text/javascript; charset=utf-8'],
    '/detail.js': ['detail.js', 'text/javascript; charset=utf-8'],
    '/admin.js': ['admin.js', 'text/javascript; charset=utf-8'],
    '/assets/vivay-logo.png': ['assets/vivay-logo.png', 'image/png'],
    '/favicon.ico': ['assets/vivay-logo.png', 'image/png']
};

const result = Object.fromEntries(Object.entries(assets).map(([route, [file, contentType]]) => [route, {
    contentType,
    body: readFileSync(join(root, file)).toString('base64')
}]));

writeFileSync(
    join(root, 'functions', 'generated-assets.mjs'),
    `// Generated by scripts/build-neon-assets.js. Do not edit manually.\nexport const STATIC_ASSETS = Object.freeze(${JSON.stringify(result)});\n`
);

console.log(`Prepared ${Object.keys(result).length} static assets for Neon Functions.`);
